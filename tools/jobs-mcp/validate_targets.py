"""Probe every slug in companies/candidates.yaml against Greenhouse, Ashby and Lever, and write the boards
that respond to companies/targets.yaml (with the open-role count and filtered-role count).

Usage: .venv/Scripts/python.exe tools/jobs-mcp/validate_targets.py
"""
from __future__ import annotations

import asyncio
from collections import Counter
from datetime import date

import httpx
import yaml

import jobs_core as core

CANDIDATES = core.ROOT / "companies" / "candidates.yaml"
ATS_ORDER = ["greenhouse", "ashby", "lever"]


async def probe(client: httpx.AsyncClient, sem: asyncio.Semaphore, cand: dict) -> dict | None:
    for slug in cand["slugs"]:
        for ats in ATS_ORDER:
            async with sem:
                try:
                    raws = await core.fetch_board(client, ats, slug)
                except Exception:  # noqa: BLE001 — 404 / bad JSON just means "not this board"
                    continue
            if not raws:
                continue  # empty boards are often stale slugs; try the next guess
            jobs = [core._normalize(ats, slug, cand["name"], cand["tier"], r) for r in raws]
            relevant = [j for j in jobs if core.passes(j, ["US", "REMOTE", "IN"], None)]
            top_tracks = [t for t, _ in Counter(j.track for j in relevant if j.track).most_common(3)]
            return {"name": cand["name"], "ats": ats, "slug": slug, "tier": cand["tier"],
                    "focus": cand["focus"], "tracks": top_tracks,
                    "open_roles": len(jobs), "relevant_roles": len(relevant)}
    return None


async def main() -> None:
    cands = yaml.safe_load(CANDIDATES.read_text(encoding="utf-8"))["companies"]
    sem = asyncio.Semaphore(10)
    async with httpx.AsyncClient(timeout=30, follow_redirects=True,
                                 headers={"User-Agent": "jobs-mcp/0.1 (personal job search)"}) as client:
        results = await asyncio.gather(*(probe(client, sem, c) for c in cands))

    found, seen = [], set()
    for r in results:
        if r and (r["ats"], r["slug"]) not in seen:
            seen.add((r["ats"], r["slug"]))
            found.append(r)
    unmatched = [c for c, r in zip(cands, results) if r is None]
    missing = [c["name"] for c in unmatched]
    found.sort(key=lambda r: (r["tier"], -r["relevant_roles"]))

    header = (f"# Generated by tools/jobs-mcp/validate_targets.py on {date.today()}. Edit candidates.yaml and re-run.\n"
              f"# not_on_ats = Workday / custom careers sites: check manually or via web search.\n")
    body = yaml.safe_dump(
        {"companies": found,
         "not_on_ats": [{"name": c["name"], "tier": c["tier"], "focus": c["focus"]} for c in unmatched]},
        sort_keys=False, allow_unicode=True, width=200)
    core.TARGETS.write_text(header + body, encoding="utf-8")
    print(f"confirmed boards: {len(found)}  missing: {len(missing)}  "
          f"relevant roles now: {sum(r['relevant_roles'] for r in found)}")
    print("missing:", ", ".join(missing))


if __name__ == "__main__":
    asyncio.run(main())
